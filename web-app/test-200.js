async function run() {
  var l = await (new Promise(function (rs) { var d = JSON.stringify({ username: '质检员小王', password: '123456' }); var r = http.request({ hostname: '127.0.0.1', port: 3000, path: '/api/auth/login', method: 'POST', headers: { 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(d) } }, function (res) { var b = ''; res.on('data', function (c) { b += c }); res.on('end', function () { rs(JSON.parse(b)) }) }); r.write(d); r.end() }));
  T = l.token;

  var total = suite.length;
  console.log('Running ' + total + ' QA tests...\n');

  var batch = 25;
  for (var i = 0; i < suite.length; i += batch) {
    var chunk = suite.slice(i, i + batch);
    var results = await Promise.all(chunk.map(function (tc) {
      return ap({ question: tc.q }).then(function (r) {
        var ans = r.answer || '';
        var ok = tc.expect.every(function (e) { return ans.indexOf(e) >= 0 });
        if (!ok) {
          var miss = tc.expect.filter(function (e) { return ans.indexOf(e) < 0 });
          return { q: tc.q, ok: false, miss: miss, ans: ans.substring(0, 180).replace(/\n/g, ' ') };
        }
        return { q: tc.q, ok: true };
      }).catch(function (e) { return { q: tc.q, ok: false, miss: ['ERROR:' + e.message], ans: '' } });
    }));
    results.forEach(function (r) { if (r.ok) p++; else fails.push(r) });
    process.stdout.write('  ' + Math.round((i + chunk.length) / total * 100) + '%  \r');
  }

  console.log('\n\n═══════════════════════');
  console.log('Total: ' + total + ' | Pass: ' + p + ' | Fail: ' + fails.length + ' | Rate: ' + Math.round(p / total * 100) + '%');
  if (fails.length > 0) {
    console.log('\nFailures (' + fails.length + '):');
    fails.forEach(function (f) { console.log('❌ [' + f.miss.join(', ') + '] Q: ' + f.q + ' — ' + f.ans) });
  } else {
    console.log('🎉 All passed!');
  }
  process.exit(fails.length > 0 ? 1 : 0);
}
